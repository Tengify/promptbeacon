import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('work/screenshots',{recursive:true});
const browser=await chromium.launch({headless:true});
const errors=[];const results=[];
try {
 const context=await browser.newContext({viewport:{width:880,height:820},colorScheme:'light'});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:1420');await page.waitForLoadState('networkidle');
 assert.equal(await page.getByRole('heading',{name:'Know before you prompt.'}).count(),1);
 assert.match(await page.locator('.browser-note').textContent(),/Browser preview/);
 await page.screenshot({path:'work/screenshots/beacon-light.png',fullPage:true});
 await page.getByLabel('Model',{exact:true}).selectOption('Claude Opus');
 assert.equal(await page.locator('#sample-label').textContent(),'Claude Opus');
 await page.getByLabel('Effort',{exact:true}).selectOption('Low');
 assert.equal(await page.locator('#sample-bars .filled').count(),1);
 await page.getByLabel('Beacon style').selectOption('tint');
 await page.getByLabel('Tint strength').evaluate(input=>{input.value='9';input.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.getByLabel('Badge position').selectOption('bottom-left');
 await page.getByRole('button',{name:'Pause beacon'}).click();await page.waitForFunction(()=>document.querySelector('#save-status')?.textContent==='Saved locally');
 await page.reload();await page.waitForLoadState('networkidle');
 assert.equal(await page.getByLabel('Beacon style').inputValue(),'tint');
 assert.equal(await page.getByLabel('Badge position').inputValue(),'bottom-left');
 assert.equal(await page.getByRole('button',{name:'Resume beacon'}).count(),1);
 results.push('Appearance and pause state survive restart');
 await page.getByRole('button',{name:'Model colors',exact:true}).click();
 await page.getByLabel('Model name',{exact:true}).fill('Custom Codex');
 await page.getByLabel('Match phrase',{exact:true}).fill('gpt-6.1-sol');
 await page.getByRole('button',{name:'Add model'}).click();
 assert.match(await page.locator('#rule-error').textContent(),/unique/);
 await page.getByLabel('Match phrase',{exact:true}).fill('custom-codex');
 await page.getByRole('button',{name:'Add model'}).click();
 assert.equal(await page.getByLabel('Color for Custom Codex',{exact:true}).count(),1);
 await page.waitForFunction(()=>document.querySelector('#save-status')?.textContent==='Saved locally');
 await page.reload();await page.waitForLoadState('networkidle');await page.getByRole('button',{name:'Model colors',exact:true}).click();
 assert.equal(await page.getByLabel('Color for Custom Codex',{exact:true}).count(),1);
 await page.getByRole('button',{name:'Remove Custom Codex',exact:true}).click();
 assert.equal(await page.getByLabel('Color for Custom Codex',{exact:true}).count(),0);
 results.push('Model add, duplicate validation, persistence, and removal');
 await page.screenshot({path:'work/screenshots/colors-light.png',fullPage:true});
 await page.getByRole('button',{name:'Connections',exact:true}).click();
 assert.match(await page.locator('#integration-code').textContent(),/desktop application/);
 assert.equal(await page.getByRole('button',{name:'Open Accessibility permissions'}).isVisible(),false);
 results.push('Browser preview never claims desktop detection');
 await page.screenshot({path:'work/screenshots/connections-light.png',fullPage:true});
 await page.setViewportSize({width:640,height:780});
 await page.getByRole('button',{name:'Beacon',exact:true}).click();await page.screenshot({path:'work/screenshots/beacon-narrow.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.emulateMedia({colorScheme:'dark'});await page.setViewportSize({width:880,height:820});
 await page.screenshot({path:'work/screenshots/beacon-dark.png',fullPage:true});
 await page.getByRole('button',{name:'Model colors',exact:true}).click();await page.screenshot({path:'work/screenshots/colors-dark.png',fullPage:true});
 results.push('Light, dark, and narrow layouts fit their viewport');
 assert.deepEqual(errors,[]);
 await writeFile('work/ui-results.json',JSON.stringify({passed:results,errors},null,2));
 console.log(JSON.stringify({passed:results,errors},null,2));
} finally { await browser.close(); }
